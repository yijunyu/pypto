//! AST -> Rust source.
//!
//! Emits code against `tile_std::tile`. Each PTO SSA `%ptoN` becomes a Rust
//! binding `tN`; function arguments become `a0, a1, ...`. The emitter does
//! nothing clever -- it walks ops in order, looks up shape/dtype for each
//! operand in the FUNCTION's own `shapes` map, and emits a matching
//! `tile_*_fNN::<R, C>(...)`
//! call. Shape mismatches surface as rustc type errors at compile time, which
//! is the whole point.

use crate::ast::*;
use crate::windows::{provably_disjoint, view_windows, Window};
use std::collections::BTreeMap;
use std::fmt::Write;

pub fn emit_module(m: &PtoModule) -> Result<String, String> {
    // A cross-core pair is refused BEFORE anything is emitted, because the
    // reason is a property of the module and not of any op in it. See
    // `cross_core_pair`.
    if let Some(why) = cross_core_pair(m) {
        return Err(why);
    }
    // The licence header comes first: these files are generated, so a header
    // prepended by hand is stripped by the next regeneration.
    let mut out = String::from(crate::emitter_tile::LICENSE_HEADER);
    writeln!(out, "// Generated by ptoas_rs -- DO NOT EDIT").unwrap();
    writeln!(out, "// Compile this file and rustc will prove that:").unwrap();
    writeln!(
        out,
        "//   * every tile shape is consistent (const generics),"
    )
    .unwrap();
    writeln!(
        out,
        "//   * every tile handle is used exactly once (move semantics)."
    )
    .unwrap();
    // `tile_std` IS the core library: it is `#![no_core]` and defines the
    // `sized` lang item itself, so a crate that pulls in Rust's `core` as well
    // fails to compile before any kernel line is read --
    // `E0152: duplicate lang item in crate tile_std: sized`. Until 2026-11-01
    // this prologue said only `#![no_std]`, which is that error, and every one
    // of the eleven artifacts that "lifted" produced a file that could not be
    // built. Nothing noticed because nothing had compiled the output; the gate
    // in `tests/lifted_kernels_compile.rs` is what makes this line load-bearing.
    // `examples/tile_softmax/kernels/src/lib.rs` carries the same three lines,
    // which is where the shape of them comes from.
    writeln!(out, "#![feature(no_core)]").unwrap();
    writeln!(out, "#![no_std]").unwrap();
    writeln!(out, "#![no_core]").unwrap();
    writeln!(
        out,
        "#![allow(unused_unsafe, unused_variables, non_snake_case)]"
    )
    .unwrap();
    writeln!(out, "use tile_std::tile::*;").unwrap();
    writeln!(out).unwrap();

    for f in &m.funcs {
        emit_func(&mut out, f, &f.shapes, &f.consts)?;
        writeln!(out).unwrap();
    }
    // Exactly one trailing newline. `end-of-file-fixer` is part of the lint gate
    // and these artefacts are byte-identity gated against a fresh emit, so an
    // emitter ending in a blank line produces a file the hook rewrites -- after
    // which the artefact no longer equals what the harness produces.
    let mut out = out.trim_end().to_string();
    out.push('\n');
    Ok(out)
}

/// Refuse a module that is TWO kernels on two different cores, with the reason
/// that survives modelling every op in it.
///
/// Seven of the corpus's 49 artifacts are one `func.func` with
/// `pto.kernel_kind<cube>` and one with `<vector>`, and the first op the lift
/// used to reach was `pto.import_reserved_buffer`, refused by the generic
/// unmodelled-op arm: "`pto.import_reserved_buffer` is not modelled, so no
/// Rust can be emitted for it". That reads as one missing op worth seven
/// artifacts. Bypassing it and recounting, as this crate keeps having to
/// learn, gives a different picture -- those files hold **20 to 26 unmodelled
/// ops each, 15 distinct mnemonics**, and eight of those mnemonics are one
/// protocol: `reserve_buffer` and `import_reserved_buffer` (a FIFO named
/// `"c2v_fifo"`, owned by the vector half and imported by the cube half
/// through a `peer_func` symbol), `aic_initialize_pipe` and
/// `aiv_initialize_pipe` (its two ends), `tpush_to_aiv`, `tpop_from_aic` and
/// `tfree_from_aic` (the transfer), and `set_quant_vector`.
///
/// Three walls, each measured, any one of them sufficient:
///
/// 1. **The target API has no cross-core vocabulary at all.** Not a missing
///    wrapper with an intrinsic one layer down -- the usual shape of a gap
///    here -- but zero: `crates/tile_std/src` contains no occurrence of
///    `c2v`, `aic` or `aiv`. The tile API is per-kernel, `Tile<R, C, T>`
///    values inside one function, and this lift emits one Rust `fn` per
///    `func.func`. There is no form for "this tile leaves this kernel through
///    a FIFO that a named sibling kernel consumes".
///
/// 2. **A tile changes dtype in flight, with no op to lift.** The cube pushes
///    `loc=acc, dtype=i32` and the vector pops `dtype=f16`. Nothing in either
///    function performs that conversion: it is the `acc_push_epilogue`
///    attribute on the pipe initialisation -- `quant = deqf16_vec,
///    layout = nz2nd` -- done by the fixpipe during the transfer. An op-by-op
///    lift has nothing to emit for it, and emitting nothing would silently
///    change the program.
///
/// 3. **An emit-time knob decides correctness and the launch.**
///    `TILERS_GMM_BLOCKS` (default 1) and `TILERS_GMM_NB` (default 256) are
///    read from the environment by `mlir_to_pto`, and above 1 blocks is not a
///    speed setting: each block then sees only `hidden / blocks` columns, so
///    the per-row absmax the quantisation needs is reduced across blocks
///    through a GM workspace and a grid-wide barrier. That emitter's own
///    comment says why it cannot be inferred later -- "the block count has to
///    be fixed at emit time, and the launch has to match it", because the
///    vector half's pop count is a straight-line constant. Four of the seven
///    artifacts are that pair of knobs at 8/16/32/64 blocks against
///    256/128/64/32 columns, same `16x4096 @ 4096x4096` call throughout.
///    A lifted Rust kernel carries neither the knob nor a blockDim.
///
/// So this is the same closure as the whole-kernel `__tile_*` tier, reached by
/// a different route. See `tests/cross_core_pair.rs`.
fn cross_core_pair(m: &PtoModule) -> Option<String> {
    let cube = m
        .funcs
        .iter()
        .find(|f| f.kind == Some(KernelKind::Cube))?;
    let vector = m
        .funcs
        .iter()
        .find(|f| f.kind == Some(KernelKind::Vector))?;
    Some(format!(
        "`{}` and `{}` are the cube and vector halves of ONE kernel, linked by a          cross-core FIFO, and the tile API has no form for that: `tile_std` contains no          occurrence of `c2v`, `aic` or `aiv`, so this is not a missing wrapper over an          existing intrinsic. The accumulator tile also changes dtype in flight -- pushed          i32, popped f16 -- by the `acc_push_epilogue` attribute on the pipe rather than          by any op a lift could emit. And the geometry is an emit-time environment knob          (`TILERS_GMM_BLOCKS`, `TILERS_GMM_NB`) that above 1 adds a cross-block reduction          and fixes the blockDim the kernel must be launched at, so the lifted source would          not determine the artifact. Modelling the unmodelled ops would not change any of          the three",
        cube.name, vector.name
    ))
}

fn emit_func(
    out: &mut String,
    f: &PtoFunc,
    shapes: &BTreeMap<Ssa, TileShape>,
    consts: &BTreeMap<Ssa, i64>,
) -> Result<(), String> {
    // Build an SSA -> Rust-identifier map. Function args get short aliases
    // `a0`, `a1`, ...; everything else is renamed during emission.
    let mut names: BTreeMap<Ssa, String> = BTreeMap::new();
    let mut arg_list = String::new();
    for (i, (ssa, ty)) in f.args.iter().enumerate() {
        let n = format!("a{i}");
        names.insert(ssa.clone(), n.clone());
        if i > 0 {
            arg_list.push_str(", ");
        }
        write!(arg_list, "{n}: {}", rust_arg_ty(ty)).unwrap();
    }
    writeln!(out, "#[no_mangle]").unwrap();
    writeln!(
        out,
        "pub unsafe extern \"C\" fn {}({}) {{",
        f.name, arg_list
    )
    .unwrap();

    // Where each view lands in the buffer it aliases. Decided once for the
    // whole function because two consumers need the same answer: the
    // `PartitionView` arm, which folds the offset into the address, and
    // `barrier_blocker`, which can only tell two stores apart by their
    // addresses. Two copies of this arithmetic would be two chances to
    // disagree about whether a store overlaps another.
    let windows = view_windows(&f.ops, consts);

    // SSA -> the constant's own spelling, so the scalar arms can write the
    // literal the artifact carried instead of refusing for want of it. The
    // integer view (`consts`) loses the float width, and several ops need the
    // float itself.
    let mut scalars: BTreeMap<Ssa, ConstVal> = BTreeMap::new();
    for op in &f.ops {
        if let PtoOp::ScalarConst { dst, value } = op {
            scalars.insert(dst.clone(), value.clone());
        }
    }

    // Whether this function's barriers can be dropped is a property of the
    // WHOLE function, not of a barrier, so it is decided once here. See
    // `barrier_blocker`.
    //
    // Decided BEFORE the linearity check below, and the order is not a
    // preference. The first blocker `barrier_blocker` looks for is an in-place
    // write -- one op naming a tile as both input and output -- and under one
    // the read count is counting reads of a buffer whose CONTENTS change in
    // between, so "this tile is read twice" would be describing something the
    // AST does not mean. The sharing has to be resolved before linearity is a
    // question.
    let blocker = barrier_blocker(&f.ops, &windows);
    if f.ops.iter().any(|op| matches!(op, PtoOp::Barrier { .. })) {
        if let Some(why) = &blocker {
            return Err(format!(
                "`pto.barrier` cannot be dropped in `{}`: {why}. The tile API \
                 cannot express a barrier either -- `mlir_to_pto` SKIPS any \
                 `__tile_pipe_barrier` line, so a call would not survive a \
                 recompile -- which leaves refusing as the only option",
                f.name
            ));
        }
    }

    // `Tile<R, C, T>` is not `Copy`, so a tile-API call MOVES its operand and
    // a PTO tile read twice is `E0382: use of moved value` in the output.
    // `linearize` has already re-loaded every such tile it could; what is left
    // is one whose value cannot be reproduced -- a compute result, a cast, a
    // matmul accumulator -- or one read after a `pto.tstore`, past which this
    // crate will not claim what memory holds.
    //
    // The alternative to refusing would be a tile copy, and the tile API has
    // none on purpose: `Tile` is "intentionally not `Copy`: each tile must be
    // consumed by exactly one store operation, preventing double-DMA bugs",
    // and `tile_copy_f32` is one of the three names a previous version of this
    // emitter invented for itself.
    let reads = read_counts(&f.ops);

    for op in &f.ops {
        // Droppable, by the decision above: a blocked barrier returned there.
        if matches!(op, PtoOp::Barrier { .. }) {
            continue;
        }
        // Checked per OP rather than once for the function, so that the op
        // ORDER decides which refusal a reader sees. An unfused softmax reads
        // its input twice AND holds a row-expansion this lift cannot write;
        // both refusals are true, and the one naming an op is the one that can
        // be acted on, so it has to come from the earlier op rather than from
        // a whole-function check that runs first by construction.
        for t in op.tile_reads() {
            let n = reads.get(t).copied().unwrap_or(0);
            if n > 1 {
                return Err(format!(
                    "`{}` is read by {n} ops in `{}`, and `tile_std`'s `Tile` is not `Copy`, \
                     so the lift would move it twice. A tile loaded from memory is re-loaded \
                     instead; this one is not -- it is produced by a compute op, or it is \
                     read after a `pto.tstore` -- and the tile API has no copy to duplicate \
                     it with",
                    t.0, f.name
                ));
            }
        }
        emit_op(out, op, shapes, consts, &scalars, &mut names, &windows)?;
    }
    writeln!(out, "}}").unwrap();
    Ok(())
}

/// How many ops read each tile.
///
/// Top level only, for the same reason `view_windows` is: a region's body is
/// never emitted, and counting half a function would be worse than not
/// counting it. An op naming one tile TWICE (`tmul ins(%x, %x)`, the square
/// that opens every rms-norm chain) counts as two, which is what matters here
/// -- it is two moves of one value in a single Rust call.
fn read_counts(ops: &[PtoOp]) -> BTreeMap<&Ssa, usize> {
    let mut reads: BTreeMap<&Ssa, usize> = BTreeMap::new();
    for op in ops {
        for t in op.tile_reads() {
            *reads.entry(t).or_default() += 1;
        }
    }
    reads
}

/// Why this function's `pto.barrier` ops cannot be dropped, or `None` if they
/// can be.
///
/// A `pto.barrier` orders PTO ops against each other. The lifted Rust orders
/// its calls two ways: statement order, which the emitter preserves, and value
/// dependencies, because every tile-API call takes and returns `Tile<R, C, T>`
/// by value. Where an ordering is carried by those, a barrier adds nothing the
/// generated Rust could say -- and nothing it could say anyway:
/// `mlir_to_pto.rs` matches `__tile_pipe_barrier` and `continue`s, so a call
/// emitted here would be deleted on the way back to PTO. Its own op table
/// records the policy: "`__tile_pipe_barrier` | (suppressed -- PTO/ptoas
/// inserts sync automatically)".
///
/// Measured end to end from checked-in artifacts, not from that comment:
/// `examples/tile_softmax/kernels/src/lib.rs` makes **0** barrier calls, its
/// `.acl.pto` has **0** `pto.barrier`, and the `ptoas` output beside it has
/// **5** `pipe_barrier` (1 `PIPE_ALL`, 4 `PIPE_V`). The sync is manufactured
/// below this level.
///
/// Two orderings are NOT carried by Rust values, so each is a blocker:
///
///   1. **In-place tile writes** -- one op naming the same SSA as both an input
///      and an output. PTO tiles are mutable named buffers; the tile API has no
///      in-place form, so two PTO ops sharing a buffer become two Rust values
///      and the shared-storage hazard disappears from the output rather than
///      being represented. 30 op lines across the corpus do this, in the
///      swiglu and GMM kernels.
///   2. **Memory-mediated dependencies** -- a `pto.tstore` before a later
///      `pto.tload` or `pto.tstore`. Those go through raw pointers, which
///      Rust's value graph does not model.
///
/// (2) asks about an ORDERING, so it only bites where the two accesses can
/// reach the same element. Once a view's offset resolves to a constant its span
/// is known exactly, and two spans of one buffer that cannot overlap have no
/// ordering to carry -- see [`provably_disjoint`], which answers `false`
/// whenever anything is unknown. That is not a relaxation for its own sake: the
/// rope kernels write the two halves of their output through two views of one
/// pointer, `[%c0, %c0]` and `[%c0, %c16]`, and a rule that cannot see the
/// offsets has to refuse them.
///
/// This is deliberately NOT the claim that `ptoas --enable-insert-sync`
/// reconstructs every barrier. `mlir_to_pto.rs:1036` states the opposite for
/// one pattern -- "The two halves of the two-sided bound are a read-after-write
/// and get their own barrier; ptoas does not insert one here" -- and that
/// cannot be checked without `ptoas`, which is not on this machine. The rule
/// above needs no such claim: it asks only whether the ordering survives into
/// the generated Rust, and refuses when it would not.
fn barrier_blocker(
    ops: &[PtoOp],
    windows: &BTreeMap<Ssa, Result<Window, String>>,
) -> Option<String> {
    for op in ops {
        if let Some((dst, srcs)) = in_place_operands(op) {
            if srcs.contains(&dst) {
                return Some(format!(
                    "`{}` is written in place (it is both an input and the output \
                     of one op), so two PTO ops share a buffer that the lifted \
                     Rust represents as two separate values",
                    dst.0
                ));
            }
        }
    }
    // Every view already stored to, so a later access is compared against all
    // of them and not only the most recent -- three stores where the third
    // overlaps the first is the case a single `bool` cannot see.
    let mut stored: Vec<&Ssa> = Vec::new();
    for op in ops {
        match op {
            PtoOp::TStore { view, .. } => {
                if let Some(prev) = stored
                    .iter()
                    .find(|p| !provably_disjoint(windows, view, p))
                {
                    return Some(format!(
                        "a second `pto.tstore` (to `{}`) follows one to `{}` that it is not \
                         known to miss, and a store-to-store ordering goes through raw \
                         pointers, which the lifted Rust does not model",
                        view.0, prev.0
                    ));
                }
                stored.push(view);
            }
            PtoOp::TLoad { view, .. } => {
                if let Some(prev) = stored
                    .iter()
                    .find(|p| !provably_disjoint(windows, view, p))
                {
                    return Some(format!(
                        "`pto.tload` from `{}` follows a `pto.tstore` to `{}` that it is not \
                         known to miss, and that dependency goes through raw pointers, which \
                         the lifted Rust does not model",
                        view.0, prev.0
                    ));
                }
            }
            // A region could hide either hazard, so recurse rather than
            // certify a function by its top level alone.
            PtoOp::For { body, .. } => {
                if let Some(why) = barrier_blocker(body, windows) {
                    return Some(why);
                }
            }
            PtoOp::If {
                then_body,
                else_body,
                ..
            } => {
                if let Some(why) = barrier_blocker(then_body, windows) {
                    return Some(why);
                }
                if let Some(why) = barrier_blocker(else_body.as_deref().unwrap_or(&[]), windows) {
                    return Some(why);
                }
            }
            _ => {}
        }
    }
    None
}

/// `(output, inputs)` for the ops that can name one tile twice.
fn in_place_operands(op: &PtoOp) -> Option<(Ssa, Vec<Ssa>)> {
    Some(match op {
        PtoOp::BinOp { dst, a, b, .. } => (dst.clone(), vec![a.clone(), b.clone()]),
        PtoOp::BinOpScalar { dst, a, .. } => (dst.clone(), vec![a.clone()]),
        PtoOp::UnOp { dst, src, .. } => (dst.clone(), vec![src.clone()]),
        PtoOp::RowReduce { dst, src, .. } => (dst.clone(), vec![src.clone()]),
        PtoOp::RowExpand { dst, src } => (dst.clone(), vec![src.clone()]),
        PtoOp::RowExpandSub { dst, src, red }
        | PtoOp::RowExpandDiv { dst, src, red }
        | PtoOp::RowExpandMul { dst, src, red } => {
            (dst.clone(), vec![src.clone(), red.clone()])
        }
        PtoOp::TMatmul { dst, lhs, rhs } => (dst.clone(), vec![lhs.clone(), rhs.clone()]),
        PtoOp::TMov { dst, src } => (dst.clone(), vec![src.clone()]),
        PtoOp::Cvt { dst, src, .. } => (dst.clone(), vec![src.clone()]),
        PtoOp::Transpose { dst, src, scratch } => {
            (dst.clone(), vec![src.clone(), scratch.clone()])
        }
        PtoOp::RmsNorm { dst, src, .. } => (dst.clone(), vec![src.clone()]),
        PtoOp::Softmax { dst, src } => (dst.clone(), vec![src.clone()]),
        _ => return None,
    })
}

/// Resolve a dtype to its tile-API name suffix, or refuse.
///
/// The emitter builds intrinsic names by interpolating this suffix
/// (`tile_load_{dt}`), so a dtype with no suffix has no name to build and the
/// lift must stop here. Returning a plausible string instead would emit Rust
/// that names an intrinsic `tile_std` does not define -- which fails at the
/// far end of the pipeline, in a compile error about a missing function,
/// pointing at generated code rather than at the dtype that caused it.
fn tile_suffix(dt: DType) -> Result<&'static str, String> {
    dt.tile_suffix().ok_or_else(|| dt.unsupported_for_lift())
}

/// Which `tile_<stem>_<dtype>` SAFE WRAPPERS `tile_std::tile` actually
/// exports, measured from its source on 2026-11-01.
///
/// A suffix that exists is not a wrapper that exists, and that gap was live.
/// `tile_suffix` above refuses `i16`/`i32`/`u64` and lets `f32`/`f16`/`bf16`/
/// `i8` through, after which each arm interpolated its own stem -- so the lift
/// returned `Ok` for four ops whose composed name `tile_std` does not define
/// at any dtype:
///
/// | emitted                   | in `tile_std`                      |
/// |---------------------------|------------------------------------|
/// | `tile_row_expand_sub_f32` | nothing, at any layer              |
/// | `tile_row_expand_div_f32` | nothing, at any layer              |
/// | `tile_copy_f32`           | nothing (`__tile_duplicate_*` is a |
/// |                           | scalar FILL over the buffer API)   |
/// | `tile_abs_f32`            | `__tile_abs_f32` only, no wrapper  |
///
/// and for every f16 arm of nine more stems. The first three are absent
/// outright; the fourth is the dangerous shape, because searching `tile_std`
/// for `abs` finds `__tile_abs_f32` and the arm looks backed. The lift emits
/// safe wrappers taking `Tile<R, C, T>`; an `extern "C"` `__tile_*` over `u32`
/// handles is a different API and cannot be called in its place. That is the
/// same two-layer confusion that put five casts in the `pto.tcvt` arm when
/// only three wrapper pairs exist.
///
/// The table is per-dtype rather than per-stem because the gap is per-dtype:
/// `add` has f32 and f16, `sub` has only f32. A stem-level allowlist would
/// have re-admitted `tile_sub_f16`.
///
/// `tests/emitted_names_resolve.rs` checks every row against `tile_std`'s
/// source, so this going stale is a test failure rather than a compile error
/// in generated code.
pub const WRAPPERS: &[(&str, &[&str])] = &[
    ("add", &["f32", "f16"]),
    ("sub", &["f32"]),
    ("mul", &["f32"]),
    ("div", &["f32"]),
    ("max", &["f32"]),
    ("min", &["f32"]),
    ("exp", &["f32"]),
    ("neg", &["f32"]),
    ("reduce_max", &["f32"]),
    ("reduce_sum", &["f32"]),
    ("matmul", &["f32", "f16"]),
    ("softmax", &["f32", "f16"]),
    ("load", &["f32", "f16", "i8"]),
    ("store", &["f32", "f16", "i8"]),
    ("transpose", &["f32"]),
    ("rms_norm", &["f32"]),
    // The scalar arm: `tile_scale_f32` is the only `tile_scale_*` wrapper in
    // `tile_std`, though `__tile_scale_f16` exists at the buffer API.
    ("scale", &["f32"]),
    ("adds", &["f32"]),
    ("subs", &["f32"]),
    ("row_expand", &["f32"]),
];

/// `tile_<stem>_<dtype>` when `tile_std` exports it, else a refusal that names
/// the composed name and the dtypes that would have worked.
///
/// `pto_op` is the mnemonic from the artifact, so the refusal points at the
/// input line and not only at the generated name -- the sweep rejects any
/// refusal that quotes nothing present in its input.
fn wrapper(stem: &str, dt: DType, pto_op: &str) -> Result<String, String> {
    let dts = tile_suffix(dt)?;
    match WRAPPERS.iter().find(|(s, _)| *s == stem) {
        Some((_, ok)) if ok.contains(&dts) => Ok(format!("tile_{stem}_{dts}")),
        Some((_, ok)) => Err(format!(
            "`{pto_op}` at dtype `{}` would lift to `tile_{stem}_{dts}`, which \
             tile_std does not export; it has `tile_{stem}_*` for {ok:?} only",
            dt.pto_spelling(),
        )),
        None => Err(format!(
            "`{pto_op}` would lift to `tile_{stem}_{dts}`, and tile_std exports \
             no `tile_{stem}_*` wrapper at any dtype",
        )),
    }
}

fn rust_arg_ty(ty: &PtoType) -> String {
    match ty {
        PtoType::Ptr(dt) => format!("*mut {}", dt.rust_scalar()),
        // These aren't used as func args in practice, but map them for completeness:
        PtoType::TensorView { rank: 2, dtype } => format!("*mut {}", dtype.rust_scalar()),
        // A rank-N tensor view is the same hazard as `PartitionViewNd`, one op
        // upstream: `*mut T` would claim a contiguity an NZ/fractal layout does
        // not have. Kept total and made to look wrong.
        PtoType::TensorView { rank, dtype } => {
            format!("/* rank-{rank} tensor view */ *mut {}", dtype.rust_scalar())
        }
        PtoType::PartitionView { dtype, .. } => format!("*mut {}", dtype.rust_scalar()),
        // A rank-N view has no rows/cols, so a `*mut T` argument would claim a
        // contiguity the layout does not have. It never appears in a function
        // SIGNATURE in the corpus; this keeps the match total and makes the
        // wrong-looking thing look wrong.
        PtoType::PartitionViewNd { dtype, .. } => {
            format!("*mut {} /* rank-N fractal view */", dtype.rust_scalar())
        }
        PtoType::TileBuf { .. } => "u32".into(),
    }
}

/// An index operand as an integer: a literal, or an SSA the parser recorded in
/// `consts`. `None` for anything else -- a loop-variant `%r`, or the `?` the
/// reverse emitter used to write.
pub(crate) fn resolve(consts: &BTreeMap<Ssa, i64>, operand: &str) -> Option<i64> {
    if let Ok(v) = operand.parse::<i64>() {
        return Some(v);
    }
    consts.get(&Ssa(operand.to_string())).copied()
}

fn emit_op(
    out: &mut String,
    op: &PtoOp,
    shapes: &BTreeMap<Ssa, TileShape>,
    consts: &BTreeMap<Ssa, i64>,
    scalars: &BTreeMap<Ssa, ConstVal>,
    names: &mut BTreeMap<Ssa, String>,
    windows: &BTreeMap<Ssa, Result<Window, String>>,
) -> Result<(), String> {
    match op {
        PtoOp::ScalarConst { .. } => {
            // Constants are folded into const-generic parameters at use sites;
            // no Rust line needed here.
        }
        PtoOp::BlockQuery { dst, which, .. } => {
            // The function EXISTS -- `tile_std::get_block_idx` /
            // `get_block_num`, extern fns at the crate root returning `usize`
            // (tile_std/src/lib.rs:94-95) -- and this refusal used to say so
            // and stop there, which read as a one-line import fix worth the 23
            // artifacts that hit it. It is not one.
            //
            // `mlir_to_pto` matches ANY input line containing `get_block_idx`
            // and replaces it with a comment, so a lifted kernel calling it
            // produces no PTO at all -- the same wall `pto.barrier` hits. And
            // the `scf.for` grid-stride loop that every one of these artifacts
            // wraps its body in is not a translation of a source loop either:
            // `mlir_to_pto` SYNTHESISES it from a shape test (`if ne0 > 1`),
            // along with the barriers, the allocs and the whole op chain, out
            // of one whole-kernel call. Each of those 41-line artifacts
            // descends from a single `llvm.call @__tile_mul_mv_id_*`.
            //
            // So the lift of such a file is that one call, not a loop. The
            // first version of this refusal then said the call has no Rust
            // entry point, which is true of `__tile_mul_mv_id_q8_0_f32` --
            // `tile_std` declares it in the Metal/MSL form, four `u32` buffer
            // handles and eleven `u32` dimensions, while `mlir_to_pto` matches
            // four pointers and two `i32`, and position 6 is `ne0` in one and
            // `ne01` in the other -- and NOT true of the tier. 25 of the 112
            // names that emitter dispatches on are declared with the pointer
            // contract, including `__tile_mxfp4_e8m0_to_f32`,
            // `__tile_mxfp4_unpack_f16` and `__tile_grouped_matmul_swiglu_quant`,
            // which are the intrinsics behind 18 of the 30 refused files.
            // See `tests/whole_kernel_intrinsics.rs`.
            //
            // What does hold for all of them is that the CALL DOES NOT
            // DETERMINE THE ARTIFACT. `mlir_to_pto` takes its tiling from four
            // environment knobs read at emit time, so one call expands into
            // different kernels on different runs: `sw_e8_r16`, `_r32`, `_r64`
            // and `_r128` are the identical
            // `__tile_mxfp4_e8m0_to_f32(s, d, 262144)` at 512, 256, 128 and 64
            // iterations of 16, 32, 64 and 128 rows, and the 4-bit unpack's
            // two sweep points are 327 and 181 lines. 15 corpus artifacts are
            // knob variants. Lifting any of them to its call would emit
            // identical Rust for files that differ -- the silent substitution
            // this crate refuses everywhere else.
            //
            // And even at the default knob the match is not checkable here:
            // the only sound criterion for "this body is the expansion of X"
            // is that re-expanding X reproduces it, which needs the forward
            // emitter. `rustc_codegen_tile` is a rustc backend in another
            // workspace and cannot be a dependency; writing the expansion out
            // by hand instead would be a second copy of a device-verified
            // chain, which its own author warns against in as many words.
            return Err(format!(
                "`{}` for `{}` is not lifted. `{}` does exist, at the `tile_std` crate \
                 root -- but importing it would not help: `mlir_to_pto` deletes any line \
                 containing `get_block_idx`, and the grid-stride `scf.for` around this op \
                 is synthesised by that emitter from the kernel's shape rather than read \
                 from its input. This file is the expansion of one whole-kernel \
                 `__tile_*` call, and that call does not determine it: the tiling comes \
                 from an emit-time environment knob, so several corpus artifacts are the \
                 SAME call at different geometries and would all lift to the same Rust",
                which.pto_mnemonic(),
                dst.0,
                which.tile_std_path(),
            ));
        }
        PtoOp::IndexCast { dst, from, to, .. } => {
            // An index_cast on its own is trivial in Rust (`as usize`), but it
            // only ever appears here to carry a block query into a partition
            // offset, and that offset is refused above. Refusing the cast too
            // keeps the diagnostic at the op the reader can act on.
            return Err(format!(
                "`arith.index_cast` {from} -> {to} for `{}` is not lifted: it \
                 exists in this dialect to carry a core-identity query into a \
                 partition offset, which this lift cannot express",
                dst.0
            ));
        }
        PtoOp::PartitionViewNd { dst, dims, .. } => {
            // Refused because the dims do NOT collapse to rows/cols: in the
            // corpus artifacts that use this, `1x4x16x16x32` has 32768
            // elements and the tile it loads into is 256x128, so neither "the
            // last dim is cols" nor "the first is rows" recovers the tile
            // shape. Picking two of the five would be a silent substitution.
            let d: Vec<String> = dims.iter().map(|x| x.to_string()).collect();
            return Err(format!(
                "partition view `{}` is a rank-{} fractal/NZ layout ({}); the tile \
                 API addresses rows and columns, and these dims do not collapse to \
                 a rows/cols pair that recovers the tile it feeds",
                dst.0,
                dims.len(),
                d.join("x"),
            ));
        }
        PtoOp::Cvt { dst, src, sat_mode } => {
            // Reconciled with `pto-rs-viewpoint-rebase`, which had wired this
            // arm while this branch only refused it. Three corrections came out
            // of putting the two side by side:
            //
            // 1. This branch's refusal named five liftable pairs from the
            //    `__tile_cast_*` INTRINSICS (bf16_f32, f16_f32, f32_bf16,
            //    f32_f16, i8_f32). The lift emits the safe `tile_std::tile`
            //    wrappers, and only THREE of those exist as wrappers --
            //    `tile_cast_f32_f16`, `tile_cast_f16_f32`, `tile_cast_i8_f32`
            //    (measured 2026-11-01 in tile_std/src/tile.rs). bf16 has the
            //    intrinsic and no wrapper, so a five-pair table would have
            //    emitted two names that do not resolve. Counting at the wrong
            //    API layer is this crate's recurring trap -- cf.
            //    `__tile_cast_f16_to_f32`, which a name search finds first and
            //    which is the BUFFER api over `UbBuf`.
            // 2. `sat_mode` decides what an out-of-range value becomes, and no
            //    `tile_std` cast takes one. That branch refused an attributed
            //    `tcvt` rather than lower it to a cast with silently different
            //    overflow behaviour; this branch was carrying `sat_mode` for
            //    fidelity but had nowhere to spend it. Together they are the
            //    right pair: carry it, and let its presence be the refusal.
            // 3. A cast must not change shape, so that is checked rather than
            //    assumed.
            let s_sh = shape_of(shapes, src)?;
            let d_sh = shape_of(shapes, dst)?;
            let (s_dt, d_dt) = (s_sh.dtype.pto_spelling(), d_sh.dtype.pto_spelling());
            if let Some(mode) = sat_mode {
                return Err(format!(
                    "`pto.tcvt` {s_dt}->{d_dt} for `{}` carries `sat_mode = {mode}`, and \
                     no tile_std cast takes a saturation mode; lowering it would silently \
                     change what an out-of-range value becomes",
                    dst.0
                ));
            }
            if (s_sh.rows, s_sh.cols) != (d_sh.rows, d_sh.cols) {
                return Err(format!(
                    "`pto.tcvt` for `{}` changes shape ({}x{} -> {}x{}); a cast must not",
                    dst.0, s_sh.rows, s_sh.cols, d_sh.rows, d_sh.cols
                ));
            }
            // Only 97 of the corpus's 188 `tcvt` instances are pairs the
            // wrappers cover; the other 91 are i8->i16/si8/f16 and f32->i32
            // conversions that have no intrinsic at all, refused by name rather
            // than lowered to a plausible-looking wrong one.
            let fname = match (s_dt, d_dt) {
                ("f16", "f32") => "tile_cast_f16_f32",
                ("f32", "f16") => "tile_cast_f32_f16",
                ("i8", "f32") => "tile_cast_i8_f32",
                _ => {
                    return Err(format!(
                        "`pto.tcvt` {s_dt}->{d_dt} for `{}` cannot be lifted: the tile API \
                         has safe casts for f16->f32, f32->f16 and i8->f32 only (bf16->f32 \
                         and f32->bf16 exist as `__tile_cast_*` intrinsics with no wrapper)",
                        dst.0
                    ))
                }
            };
            let src_n = lookup(names, src)?;
            let dst_n = lookup(names, dst)?;
            writeln!(
                out,
                "    let {dst_n} = {fname}::<{r}, {c}>({src_n});",
                r = s_sh.rows,
                c = s_sh.cols,
            )
            .unwrap();
        }
        PtoOp::Transpose { dst, src, .. } => {
            // Ported from `pto-rs-viewpoint-rebase`, shape check included.
            // `tile_transpose_f32::<R, C>` takes `Tile<R, C, f32>` and returns
            // `Tile<C, R, f32>`, so the const args are the SOURCE shape and the
            // destination must be its swap. Checked rather than assumed: a
            // `ttrans` whose declared output is not the transpose of its input
            // is not a transpose, and emitting one anyway would hand rustc a
            // shape it would accept.
            let s = shape_of(shapes, src)?;
            let d = shape_of(shapes, dst)?;
            if s.dtype != DType::F32 || d.dtype != DType::F32 {
                return Err(format!(
                    "`pto.ttrans` for `{}` is {}->{}: tile_std has `tile_transpose_f32` \
                     only (`__tile_transpose_f16` exists as an intrinsic with no wrapper)",
                    dst.0,
                    s.dtype.pto_spelling(),
                    d.dtype.pto_spelling()
                ));
            }
            if (d.rows, d.cols) != (s.cols, s.rows) {
                return Err(format!(
                    "`pto.ttrans` output `{}` is {}x{}, not the transpose of its {}x{} input",
                    dst.0, d.rows, d.cols, s.rows, s.cols
                ));
            }
            let src_n = lookup(names, src)?;
            let dst_n = lookup(names, dst)?;
            writeln!(
                out,
                "    let {dst_n} = tile_transpose_f32::<{r}, {c}>({src_n});",
                r = s.rows,
                c = s.cols,
            )
            .unwrap();
        }
        PtoOp::Unmodelled { op, .. } => {
            // The parser kept the line so the PTO round trip stays faithful;
            // that is not the same as understanding it. Nothing can be lowered
            // from an op with no AST meaning, and emitting nothing would
            // silently change the program -- which is exactly the drop this
            // variant exists to end.
            return Err(format!(
                "`{op}` is not modelled, so no Rust can be emitted for it"
            ));
        }
        PtoOp::Subview { dst, offsets, .. } => {
            // Refused on HARDWARE grounds, not for a missing intrinsic. On
            // 910B2, `LocalTensor::operator[](offset > 0)` produces wrong
            // results for vector ops -- the documented workaround is scalar
            // `GetValue`/`SetValue`, which is not what a tile-API lift emits.
            // A sub-view also has to fold its offset into an ADDRESS rather
            // than into a tile handle, and the tile API has no form for that.
            return Err(format!(
                "`pto.subview` for `{}` at offsets [{}] cannot be lifted: the tile \
                 API has no sub-view form, so there is nothing to lift INTO. \
                 (The second reason this refusal used to give -- that 910B2 \
                 mis-computes vector ops on a non-zero `LocalTensor` sub-view \
                 -- is DISPUTED and is no longer offered: the per-chip 910 \
                 knowledge base records a device run on real 910B2 / CANN 8.5.2 \
                 proving the vectorised offset form bit-identical for one \
                 shape, and the vendor recommends it. The missing API form is \
                 sufficient on its own and is not disputed.)",
                dst.0,
                offsets
                    .iter()
                    .map(|o| o.0.as_str())
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
        PtoOp::GatherB { dst, .. } => {
            // Refused because the OFFSET UNIT is part-dependent and this AST
            // records no part: on a2/a3 `tgatherb`'s offsets count 32-byte
            // blocks, on a5 they count elements. Lifting it without knowing
            // which would pick one of the two and be wrong on the other half of
            // the fleet, at exit 0.
            return Err(format!(
                "`pto.tgatherb` for `{}` cannot be lifted: its offsets count \
                 32-byte BLOCKS on a2/a3 and ELEMENTS on a5, and nothing in this \
                 module says which part it targets",
                dst.0
            ));
        }
        PtoOp::If {
            cond,
            then_body,
            else_body,
        } => {
            // Refused rather than lowered to a Rust `if`, for the same reason
            // the loop is: the two branches of every corpus instance are a
            // `pto.tmatmul` and a `pto.tmatmul.acc` on the cube, chosen on
            // whether this is the first K-step. Both are ops this lift does not
            // have, and a conditional whose arms cannot be emitted is not made
            // liftable by emitting the conditional.
            return Err(format!(
                "`scf.if {}` has two region(s) ({} then, {} else); the tile-API lift \
                 has no conditional form",
                cond.0,
                then_body.len(),
                else_body.as_ref().map_or(0, |b| b.len())
            ));
        }
        PtoOp::For {
            var,
            lb,
            ub,
            step,
            body,
        } => {
            // A Rust `for` is easy to write and would be a guess at the part
            // that matters: the bounds are SSA names usually derived from
            // `pto.get_block_idx`, so the extent is per-core, and the body
            // addresses the parent through `offsets = [%r, %c0]` -- a
            // non-origin partition view, which this lift cannot express (see
            // the PartitionView arm). Emitting the loop and refusing its body
            // would report the wrong op.
            return Err(format!(
                "`scf.for {} = {} to {} step {}` is not lifted: its {} body op(s) \
                 address the parent tensor at an offset derived from the induction \
                 variable, and this lift aliases the base pointer",
                var.0,
                lb.0,
                ub.0,
                step.0,
                body.len(),
            ));
        }
        // UNREACHABLE BY CONSTRUCTION, and kept as a refusal rather than a
        // `unreachable!`. `emit_func` is the only caller of `emit_op`, and it
        // decides the barrier question for the whole function before the loop:
        // droppable barriers are skipped, blocked ones return an error naming
        // the blocker. No region recursion reaches here either, because the
        // `scf.for` and `scf.if` arms both refuse without emitting a body.
        //
        // If that changes -- a region arm starts emitting its body -- this arm
        // is what a barrier inside it would hit, and refusing is the safe
        // answer. `barrier_in_a_region_is_still_decided_by_the_function` pins
        // the current structure so the change is visible.
        PtoOp::Barrier { pipe } => {
            return Err(format!(
                "`pto.barrier <{pipe}>` reached the op emitter, which means it \
                 bypassed the whole-function decision in `emit_func`"
            ));
        }
        PtoOp::BinOpScalar {
            kind,
            dst,
            a,
            scalar,
            scalar_ty: _,
        } => {
            // Two walls, and this arm now clears the second one. Whether a
            // wrapper exists is the wrapper table's question; whether its
            // scalar literal is available is the module's. `ScalarConst` emits
            // no Rust binding, so the value comes from the map built in
            // `emit_func` -- the parser kept the constant's spelling, and the
            // integer view loses the float itself.
            let sh = shape_of(shapes, dst)?;
            let Some(base) = kind.tile_base(sh.dtype) else {
                return Err(kind.unsupported_for_lift(sh.dtype));
            };
            let fname = wrapper(base, sh.dtype, kind.pto_mnemonic())?;
            let lit = match scalars.get(scalar) {
                Some(ConstVal::Typed { lit, ty: _ }) => Some(format!("{lit}f32")),
                Some(ConstVal::Index(n)) => Some(format!("{n}f32")),
                None => None,
            };
            let Some(lit) = lit else {
                return Err(format!(
                    "`{}`'s scalar operand `{}` is not a constant this module carries, \
                     so its value cannot be written into the lifted call",
                    kind.pto_mnemonic(),
                    scalar.0,
                ));
            };
            let a_n = lookup(names, a)?;
            let dst_n = lookup(names, dst)?;
            writeln!(
                out,
                "    let {dst_n} = {fname}::<{r}, {c}>({a_n}, {lit});",
                r = sh.rows,
                c = sh.cols,
            )
            .unwrap();
        }
        PtoOp::MakeTensorView {
            dst,
            ptr,
            dtype: _,
            shape,
            strides,
            layout,
        } => {
            // Rank and layout first, because both invalidate the aliasing the
            // rest of this arm performs. An NZ view's elements are not in
            // row-major order at all, so a contiguity check on two of five
            // dims would pass on a layout that has no rows.
            if let Some(l) = layout {
                return Err(format!(
                    "tensor view for `{}` declares `layout = {l}`; the lift aliases the \
                     base pointer as contiguous row-major, which a fractal layout is not",
                    dst.0
                ));
            }
            if shape.len() != 2 {
                return Err(format!(
                    "tensor view for `{}` is rank-{} ({}); the tile API addresses rows \
                     and columns, and these dims do not collapse to a rows/cols pair",
                    dst.0,
                    shape.len(),
                    shape.join("x")
                ));
            }
            // The Rust tile API has no "tensor view" abstraction, so this
            // aliases the raw pointer and `partition_view` reaches through it.
            // That aliasing is only sound for a CONTIGUOUS row-major parent:
            // the tile loads walk `cols` elements per row from the base, so a
            // row stride other than `cols` reads the wrong elements with no
            // diagnostic. `emitter_tile` already refuses this (it re-reads the
            // raw text, because until 2026-11-01 the AST did not carry it);
            // this path had no check at all.
            let (c, rs, cs) = (
                resolve(consts, &shape[1]),
                resolve(consts, &strides[0]),
                resolve(consts, &strides[1]),
            );
            match (c, rs, cs) {
                (Some(c), Some(rs), Some(cs)) if rs == c && cs == 1 => {}
                (Some(c), Some(rs), Some(cs)) => {
                    return Err(format!(
                        "tensor view for `{}` is strided [{rs}, {cs}] over {c} columns,                          not contiguous row-major [{c}, 1]; the lift aliases the base                          pointer and would read the wrong elements",
                        dst.0
                    ))
                }
                _ => {
                    return Err(format!(
                        "tensor view for `{}` has a shape/strides operand this lift                          cannot resolve (shape [{}, {}], strides [{}, {}]); refusing                          rather than assuming contiguity",
                        dst.0, shape[0], shape[1], strides[0], strides[1]
                    ))
                }
            }
            let ptr_n = lookup(names, ptr)?;
            let dst_n = fresh(names, dst);
            writeln!(out, "    let {dst_n} = {ptr_n};").unwrap();
        }
        PtoOp::PartitionView {
            dst,
            src,
            rows: _,
            cols: _,
            dtype: _,
            offsets,
            sizes: _,
        } => {
            // Partition views are a ptoas codegen artifact and the tile API
            // loads from the pointer directly. The offsets were not in the AST
            // until 2026-11-01, so this arm could not see them and emitted the
            // alias unconditionally: a 16-way row tiling (`offsets = [%c8,
            // %c0]` … `[%c120, %c0]`, 9 instances each in this repo's corpus)
            // lifted to sixteen kernels all reading row 0, at exit 0. 316 of
            // the corpus's 435 rank-2 partition views are non-origin.
            //
            // The fix that day was a blanket refusal, and the refusal's own
            // text said what the answer was -- "the offset has to be folded
            // into the address, not the tile". It is folded here.
            //
            // THE SECOND REASON THIS COMMENT USED TO GIVE IS WITHDRAWN. It read
            // that the ADDRESS is right "for the independent reason too: 910B2
            // mis-computes vector ops on a non-zero `LocalTensor` sub-view, so
            // a lift that moved the offset into the tile would be wrong on the
            // part". That is a DISPUTED claim stated as settled, and the
            // per-chip 910 knowledge base holds three sides of it: our own
            // standing rule, which carries no date and no receipt; the vendor's
            // own guidance, which RECOMMENDS `LocalTensor<T> view =
            // tensor[offset]` as a zero-copy view with an 11.25x geomean on a
            // production op; and a device run of ours on real 910B2 / CANN
            // 8.5.2 that found the vectorised offset form BIT-IDENTICAL, where
            // a blanket ban had been blocking an 85.7x corpus win.
            //
            // The vendor guidance also names two testable preconditions that
            // would explain the original failure without any erratum:
            // overlapping live views are UB, and 910B `Compare` requires
            // `count * sizeof(float)` to be a multiple of 256.
            //
            // Folding into the address stays correct for the reason the text
            // above already gives -- the tile API has no sub-view form -- and
            // that reason needs no hardware claim.
            //
            // Sound because the offset survives the round trip in exactly this
            // form. `mlir_to_pto` records a constant-index `llvm.getelementptr`
            // as a flat element offset (`gep_offsets`, resolved through
            // `ptr_aliases` by `mlir_parse::resolve_offset`) and `make_pv`
            // splits it back into `[off / cols, off % cols]`. Which (row, col)
            // pair comes back out need not match the one read in -- it is the
            // same flat address, split against whatever tile width the
            // recompiled kernel uses -- and the address is what the lift and
            // the tile calls both work in.
            match windows.get(dst) {
                Some(Ok(w)) => {
                    let src_n = lookup(names, src)?;
                    let dst_n = fresh(names, dst);
                    if w.off == 0 {
                        writeln!(out, "    let {dst_n} = {src_n};").unwrap();
                    } else {
                        // `wrapping_add`, not `add`: the lifted file is
                        // `#![no_core]`, where `*mut T` has only the inherent
                        // impls `tile_std::core::ptr` writes, which are
                        // `wrapping_add` / `wrapping_offset` over the
                        // `arith_offset` intrinsic. `add` is a `core` method
                        // and does not resolve -- `E0599: no method named
                        // `add` found for raw pointer `*mut f32``. It is also
                        // the form the tile API's own doc example uses
                        // (`input.wrapping_add(offset)`), and it lowers to the
                        // `llvm.getelementptr` that `mlir_to_pto` reads back
                        // as an offset; `tile_offset_ptr_f32` exists and would
                        // NOT, because no `mlir_to_*` under `rustc_codegen_tile`
                        // matches that name -- only the Triton tests do -- so a
                        // recompile would drop it as an unrecognised call and
                        // read the parent's origin instead.
                        writeln!(out, "    let {dst_n} = {src_n}.wrapping_add({});", w.off)
                            .unwrap();
                    }
                }
                Some(Err(why)) => return Err(why.clone()),
                None => {
                    return Err(format!(
                        "partition view `{}` is taken of `{}`, which this lift did not model as \
                         a contiguous rank-2 tensor view, so there is no address to fold the \
                         offsets [{}, {}] into",
                        dst.0, src.0, offsets[0], offsets[1]
                    ))
                }
            }
        }
        PtoOp::AllocTile { dst, .. } => {
            // Allocation is implicit on the Rust side -- each producer op
            // returns a fresh Tile<R, C, T>. We just reserve a name; the
            // actual binding is introduced by the consumer op (tload/matmul/etc.)
            // that fills this slot.
            fresh(names, dst);
        }
        PtoOp::TLoad { view, tile, .. } => {
            let sh = shape_of(shapes, tile)?;
            let view_n = lookup(names, view)?;
            let tile_n = lookup(names, tile)?;
            // Re-bind the tile name to the loaded Tile value.
            writeln!(
                out,
                "    let {tile_n} = {f}::<{r}, {c}>({view_n} as *const {scalar});",
                f = wrapper("load", sh.dtype, "pto.tload")?,
                r = sh.rows,
                c = sh.cols,
                scalar = sh.dtype.rust_scalar(),
            )
            .unwrap();
        }
        PtoOp::TStore { tile, view, .. } => {
            let sh = shape_of(shapes, tile)?;
            let tile_n = lookup(names, tile)?;
            let view_n = lookup(names, view)?;
            writeln!(
                out,
                "    {f}::<{r}, {c}>({view_n} as *mut {scalar}, {tile_n});",
                f = wrapper("store", sh.dtype, "pto.tstore")?,
                r = sh.rows,
                c = sh.cols,
                scalar = sh.dtype.rust_scalar(),
            )
            .unwrap();
        }
        PtoOp::BinOp { kind, dst, a, b } => {
            let sh = shape_of(shapes, dst)?;
            let a_n = lookup(names, a)?;
            let b_n = lookup(names, b)?;
            let dst_n = lookup(names, dst)?;
            let (stem, mnem) = match kind {
                BinKind::Add => ("add", "pto.tadd"),
                BinKind::Sub => ("sub", "pto.tsub"),
                BinKind::Mul => ("mul", "pto.tmul"),
                BinKind::Div => ("div", "pto.tdiv"),
                BinKind::Max => ("max", "pto.tmax"),
                BinKind::Min => ("min", "pto.tmin"),
            };
            let fname = wrapper(stem, sh.dtype, mnem)?;
            writeln!(
                out,
                "    let {dst_n} = {fname}::<{r}, {c}>({a_n}, {b_n});",
                r = sh.rows,
                c = sh.cols,
            )
            .unwrap();
        }
        PtoOp::UnOp { kind, dst, src } => {
            let sh = shape_of(shapes, dst)?;
            let src_n = lookup(names, src)?;
            let dst_n = lookup(names, dst)?;
            let (stem, mnem) = match kind {
                UnKind::Exp => ("exp", "pto.texp"),
                UnKind::Neg => ("neg", "pto.tneg"),
                UnKind::Abs => ("abs", "pto.tabs"),
                // Neither has a safe wrapper, so `wrapper` refuses with the
                // composed name. Routed through it rather than given their own
                // `return Err` so ONE place decides what is liftable: a
                // hand-written refusal here would be a second opinion, free to
                // disagree with the table the gate checks.
                UnKind::Sqrt => ("sqrt", "pto.tsqrt"),
                UnKind::Recip => ("recip", "pto.trecip"),
            };
            let fname = wrapper(stem, sh.dtype, mnem)?;
            writeln!(
                out,
                "    let {dst_n} = {fname}::<{r}, {c}>({src_n});",
                r = sh.rows,
                c = sh.cols,
            )
            .unwrap();
        }
        PtoOp::RowReduce { kind, dst, src } => {
            let src_sh = shape_of(shapes, src)?;
            let src_n = lookup(names, src)?;
            let dst_n = lookup(names, dst)?;
            let (stem, mnem) = match kind {
                RowKind::Max => ("reduce_max", "pto.trowmax"),
                RowKind::Sum => ("reduce_sum", "pto.trowsum"),
            };
            let fname = wrapper(stem, src_sh.dtype, mnem)?;
            // Tile API reduces R×C → R×1; we pass the source shape.
            writeln!(
                out,
                "    let {dst_n} = {fname}::<{r}, {c}>({src_n});",
                r = src_sh.rows,
                c = src_sh.cols,
            )
            .unwrap();
        }
        // Both row-expansions are refused, and this is NOT a dtype gap:
        // `tile_std` has no row-expand wrapper and no `__tile_row_expand_*`
        // intrinsic either, at any width. Searched 2026-11-01, both layers.
        //
        // These two ops were lifting, to `tile_row_expand_sub_f32` and
        // `tile_row_expand_div_f32`, and the whole suite was green: nothing
        // compiled the generated Rust, and the only artifacts that reach this
        // arm are softmax chains, where the fusion pass collapses the five ops
        // into `PtoOp::Softmax` and this arm never runs. The piecewise path is
        // reachable the moment a chain's intermediate escapes -- then fusion
        // declines and the lift would have emitted two names that do not exist.
        //
        // So the row-expansion forms are liftable only as part of a recognised
        // whole (softmax here, rms-norm below), which is exactly why the fusion
        // pass is load-bearing rather than an optimisation.
        PtoOp::RowExpandSub { dst, src, red } => {
            return Err(format!(
                "`pto.trowexpandsub` (`{}`, `{}` -> `{}`) is not lifted: tile_std has no \
                 row-expand wrapper or intrinsic at any dtype. It lifts only as part \
                 of a fused softmax, and this chain did not fuse",
                src.0, red.0, dst.0,
            ));
        }
        PtoOp::RowExpandDiv { dst, src, red } => {
            return Err(format!(
                "`pto.trowexpanddiv` (`{}`, `{}` -> `{}`) is not lifted: tile_std has no \
                 row-expand wrapper or intrinsic at any dtype. It lifts only as part \
                 of a fused softmax, and this chain did not fuse",
                src.0, red.0, dst.0,
            ));
        }
        PtoOp::RowExpandMul { dst, src, red } => {
            return Err(format!(
                "`pto.trowexpandmul` (`{}`, `{}` -> `{}`) is not lifted: tile_std has \
                 no row-expand wrapper or intrinsic at any dtype",
                src.0, red.0, dst.0,
            ));
        }
        // The broadcast half of the rms-norm chain. Refused on its own for the
        // same reason as the row-expansions, and with the same consequence:
        // the chain lifts whole or not at all.
        PtoOp::RowExpand { dst, src } => {
            // NO LONGER REFUSED. `tile_std::tile::tile_row_expand_f32` was
            // declared on 2026-11-04 for the delta-net's decode step, which
            // needs `(q.k)` as one value multiplied across `v`; the emitters
            // already knew `pto.trowexpand`, and only the DSL had no name for
            // it. Lifting it here also removes the reason the rms-norm chain
            // had to fuse to lift at all.
            let sh = shape_of(shapes, dst)?;
            let src_sh = shape_of(shapes, src)?;
            // The source is a REDUCTION result, and a row reduction in PTO is
            // declared as an `N x 1` column buffer whose valid part is `1 x 1`
            // -- `%pto14` is `8x1, valid=1x1`. Requiring exactly `1x1` refused
            // every real chain. What must hold is that the source carries ONE
            // value: one column, and the destination is the row it spreads over.
            if src_sh.cols != 1 {
                return Err(format!(
                    "`pto.trowexpand` needs a single-value source and `{}` is {}x{}",
                    src.0, src_sh.rows, src_sh.cols
                ));
            }
            let fname = wrapper("row_expand", sh.dtype, "pto.trowexpand")?;
            let src_n = lookup(names, src)?;
            let dst_n = lookup(names, dst)?;
            writeln!(
                out,
                "    let {dst_n} = {fname}::<{c}>({src_n});",
                c = sh.cols
            )
            .unwrap();
            return Ok(());
        }
        PtoOp::RmsNorm { dst, src, eps } => {
            // Shape from the SOURCE tile; the fused node is only built when
            // the chain's first and last ops agree on it.
            let sh = shape_of(shapes, src)?;
            let src_n = lookup(names, src)?;
            let dst_n = lookup(names, dst)?;
            let fname = wrapper("rms_norm", sh.dtype, "pto.trowexpand")?;
            // `eps` is written through as the artifact's own literal text. The
            // wrapper takes it as a runtime `f32`, so unlike rows and cols it
            // is a value argument and not a const-generic one.
            writeln!(
                out,
                "    let {dst_n} = {fname}::<{r}, {c}>({src_n}, {eps}f32);",
                r = sh.rows,
                c = sh.cols,
            )
            .unwrap();
        }
        PtoOp::TMatmul { dst, lhs, rhs } => {
            // lhs: M×K; rhs: K×N; dst: M×N. We need all three shapes.
            let l_sh = shape_of(shapes, lhs)?;
            let r_sh = shape_of(shapes, rhs)?;
            let d_sh = shape_of(shapes, dst)?;
            let l_n = lookup(names, lhs)?;
            let r_n = lookup(names, rhs)?;
            let d_n = lookup(names, dst)?;
            if l_sh.cols != r_sh.rows {
                // The operands are named so the refusal points at the file.
                // Without them this read "tmatmul shape mismatch: lhs 32x128,
                // rhs 64x32" -- true, and unattributable in a 250-line artifact
                // with several matmuls. The sweep now rejects any refusal that
                // quotes nothing present in its input.
                return Err(format!(
                    "`pto.tmatmul` K disagrees: lhs `{}` is {}x{}, rhs `{}` is {}x{} \
                     (into `{}`)",
                    lhs.0, l_sh.rows, l_sh.cols, rhs.0, r_sh.rows, r_sh.cols, dst.0
                ));
            }
            // dst must be M×N. Checked for the same reason the transpose arm
            // checks its swap: rustc would accept whatever const args we write.
            if (d_sh.rows, d_sh.cols) != (l_sh.rows, r_sh.cols) {
                return Err(format!(
                    "`pto.tmatmul` output `{}` is {}x{}, not the {}x{} its operands \
                     `{}` and `{}` produce",
                    dst.0, d_sh.rows, d_sh.cols, l_sh.rows, r_sh.cols, lhs.0, rhs.0
                ));
            }
            writeln!(
                out,
                "    let {d_n} = {f}::<{m}, {k}, {n}>({l_n}, {r_n});",
                f = wrapper("matmul", d_sh.dtype, "pto.tmatmul")?,
                m = l_sh.rows,
                k = l_sh.cols,
                n = r_sh.cols,
            )
            .unwrap();
        }
        // `pto.tmov` is a tile-to-tile copy and `tile_std` has no wrapper for
        // one. The near misses are worth naming so the question is not reopened:
        // `__tile_duplicate_f32` fills a buffer with a SCALAR, and the
        // `__tile_copy_l1_to_l0a_*` family is cube staging DMA between typed
        // buffer handles. Neither is `Tile<R, C, T> -> Tile<R, C, T>`.
        //
        // A move would be the natural lift -- the tile API is already
        // move-semantic, so `let dst = src;` copies nothing and preserves
        // single-use. That is a change to what the generated Rust MEANS, not a
        // name lookup, so it is refused rather than guessed at here.
        PtoOp::TMov { dst, src } => {
            return Err(format!(
                "`pto.tmov` (`{}` -> `{}`) is not lifted: tile_std exports no tile-to-tile \
                 copy wrapper (`__tile_duplicate_*` fills from a scalar; \
                 `__tile_copy_l1_to_l0*` is cube staging DMA)",
                src.0, dst.0,
            ));
        }
        PtoOp::Softmax { dst, src } => {
            // Shape comes from the source tile; dst has the same shape.
            let sh = shape_of(shapes, src)?;
            let src_n = lookup(names, src)?;
            let dst_n = lookup(names, dst)?;
            writeln!(
                out,
                "    let {dst_n} = {f}::<{r}, {c}>({src_n});",
                f = wrapper("softmax", sh.dtype, "pto.trowexpanddiv")?,
                r = sh.rows,
                c = sh.cols,
            )
            .unwrap();
        }
    }
    Ok(())
}

// ─── Name table helpers ────────────────────────────────────────────────────

/// Mint a Rust identifier for this SSA (if not already) and return it.
fn fresh(names: &mut BTreeMap<Ssa, String>, s: &Ssa) -> String {
    if let Some(n) = names.get(s) {
        return n.clone();
    }
    let n = ssa_to_ident(s);
    names.insert(s.clone(), n.clone());
    n
}

fn lookup(names: &BTreeMap<Ssa, String>, s: &Ssa) -> Result<String, String> {
    names
        .get(s)
        .cloned()
        .ok_or_else(|| format!("unresolved SSA `{}`", s.0))
}

/// `%pto3` -> `t3`; `%arg601` -> `arg601`.
fn ssa_to_ident(s: &Ssa) -> String {
    let raw = s.0.trim_start_matches('%');
    if let Some(rest) = raw.strip_prefix("pto") {
        format!("t{rest}")
    } else {
        raw.to_string()
    }
}

fn shape_of(shapes: &BTreeMap<Ssa, TileShape>, s: &Ssa) -> Result<TileShape, String> {
    shapes
        .get(s)
        .copied()
        .ok_or_else(|| format!("no shape for SSA `{}`", s.0))
}
